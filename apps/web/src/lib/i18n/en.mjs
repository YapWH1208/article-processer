  prompts: {
    contextDefault: () => "Tell me about this",
    authors: () => "Tell me about the authors of this paper",
    claim: ({ claim } = {}) => `Tell me more about this claim: ${claim || ""}`.trim(),
    section: ({ section } = {}) => {
      const label = SECTION_LABELS[section] || String(section || "").toLowerCase();
      return `Tell me about the ${String(label || "content").toLowerCase()} of this paper`;
    },
    readingProblem: () => "What problem does this article solve?",
    readingMethodPlain: () => "Explain the methodology in plain language.",
    readingResults: () => "What are the most important results?",
    readingLimitations: () => "What limitations should I keep in mind?",
    readingMainContribution: () => "What is the main contribution of this article?",
    readingClaim: ({ claim } = {}) => `Tell me more about this claim: ${claim || ""}`.trim(),
    readingSection: ({ section } = {}) => `Walk me through the ${String(section || "content").toLowerCase()} section.`,
    readingCompare: ({ articleTitle, compareTitles } = {}) => {
      const titles = Array.isArray(compareTitles) ? compareTitles.join(" and ") : String(compareTitles || "");
      return `Compare ${articleTitle || "this article"} with ${titles}. Focus on shared concepts, methods, results, and limitations.`;
    },
  },
